//! User pipe files: create, wrap, edit, rename and delete files in the
//! user-writable pipe folder (`modems.d`). Installed app files are never
//! written; they can only be duplicated into the user folder.
use hsrec::safepath::MODEMS;
use std::io::Write;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};

/// Mode of every file the editor writes.
pub const USER_MODE: u32 = 0o750;

/// Template for "New pipe…", derived from the conventions of the shipped
/// `commander-demod-*.rxpipe` scripts.
pub fn template(name: &str) -> String {
    let tx = name.ends_with(".txpipe");
    let (what, flow) = if tx {
        ("TX pipe", "stdin is the microphone, stdout goes to the radio's transmit audio")
    } else {
        ("RX pipe", "stdin is the radio audio, stdout goes to the speaker")
    };
    format!(
        "#!/bin/sh\n\
# {name}: Hamspot Commander {what} (user file).\n\
#\n\
# {flow}.\n\
# Both are 48 kHz mono signed 16-bit little-endian raw PCM (s16le).\n\
# $1 is a free localhost UDP port Commander reserved for this pipe\n\
# (23469 when run by hand). Use it for a decoder's UDP voice output.\n\
# Environment (set only when relevant):\n\
#   HAMSPOT_CC_EVENTS=1  keep decoder stderr; it is read as trunk events\n\
#   HAMSPOT_IDENTITY=1   keep decoder stderr for the scanner glass\n\
#   HAMSPOT_INVERT=1     the channel is set to inverted polarity\n\
#   HAMSPOT_P25_K=<csv>  dsd-fme -K key file\n\
#   HAMSPOT_<NAME>=...   decoder settings saved with a REC recording\n\
# Exit when the input ends or a tool fails; Commander restarts the pipe.\n\
set -eu\n\
port=\"${{1:-23469}}\"\n\
: \"$port\"\n\
exec cat\n"
    )
}

/// Wrapper text that runs `command` verbatim.
pub fn wrapper(name: &str, command: &str, date: &str) -> String {
    format!(
        "#!/bin/sh\n\
# {name}: generated by Hamspot Commander on {date}\n\
# from a station-file pipe command that is no longer allowed to run directly.\n\
# $1 is the UDP port Commander reserved for this pipe (unused by the\n\
# original command). stdin/stdout are 48 kHz mono s16le raw PCM.\n\
# Original command, verbatim:\n\
{command}\n"
    )
}

/// Slug for a wrapper made from `command`, e.g. `dsdccx -i -` -> `custom-dsdccx`.
pub fn slug_for(command: &str, ext: &str) -> String {
    let first = command.split_whitespace().next().unwrap_or("custom");
    let base = Path::new(first.trim_matches(['"', '\'']))
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("custom");
    let mut s: String = base
        .chars()
        .map(|c| c.to_ascii_lowercase())
        .map(|c| if c.is_ascii_alphanumeric() || c == '-' || c == '_' { c } else { '-' })
        .collect();
    s = s.trim_matches('-').to_string();
    if s.is_empty() {
        s = "pipe".into();
    }
    format!("custom-{s}{ext}")
}

/// Why `name` cannot be a new user file in `user`, given installed folders.
pub fn check_new(name: &str, user: &Path, installed: &[PathBuf]) -> Result<PathBuf, String> {
    if !MODEMS.valid_name(name) {
        return Err(format!(
            "{name}: use only a-z 0-9 . _ - and end in {}",
            MODEMS.exts.join(" or ")
        ));
    }
    if installed.iter().any(|d| d.join(name).exists()) {
        return Err(format!("{name} is an installed app file; pick another name"));
    }
    Ok(user.join(name))
}

fn user_path(name: &str, user: &Path, installed: &[PathBuf]) -> Result<PathBuf, String> {
    let path = check_new(name, user, installed)?;
    if let Ok(md) = std::fs::symlink_metadata(&path) {
        if !md.file_type().is_file() {
            return Err(format!("{name} is not a regular file"));
        }
    }
    Ok(path)
}

fn ensure_dir(user: &Path) -> Result<(), String> {
    std::fs::create_dir_all(user).map_err(|e| format!("{}: {e}", user.display()))?;
    let md = std::fs::symlink_metadata(user).map_err(|e| e.to_string())?;
    if !md.file_type().is_dir() {
        return Err(format!("{} is not a folder", user.display()));
    }
    std::fs::set_permissions(user, std::fs::Permissions::from_mode(USER_MODE)).map_err(|e| e.to_string())
}

/// Atomic write of a user pipe file with mode 0750. An existing file is
/// replaced only when `overwrite` (the user confirmed).
pub fn save(name: &str, text: &str, user: &Path, installed: &[PathBuf], overwrite: bool) -> Result<PathBuf, String> {
    let path = user_path(name, user, installed)?;
    if path.exists() && !overwrite {
        return Err(format!("{name} already exists"));
    }
    ensure_dir(user)?;
    let tmp = user.join(format!(".{name}.tmp{}", std::process::id()));
    let res = (|| {
        let mut f = std::fs::OpenOptions::new().write(true).create_new(true).mode_set().open(&tmp)?;
        f.write_all(text.as_bytes())?;
        f.sync_all()?;
        std::fs::set_permissions(&tmp, std::fs::Permissions::from_mode(USER_MODE))?;
        std::fs::rename(&tmp, &path)
    })();
    if let Err(e) = res {
        let _ = std::fs::remove_file(&tmp);
        return Err(format!("{name}: {e}"));
    }
    Ok(path)
}

trait ModeSet {
    fn mode_set(&mut self) -> &mut Self;
}
impl ModeSet for std::fs::OpenOptions {
    fn mode_set(&mut self) -> &mut Self {
        use std::os::unix::fs::OpenOptionsExt;
        self.mode(USER_MODE)
    }
}

/// Copy any pipe file (installed or user) to a new user file.
pub fn duplicate(src: &Path, name: &str, user: &Path, installed: &[PathBuf], overwrite: bool) -> Result<PathBuf, String> {
    let text = std::fs::read_to_string(src).map_err(|e| format!("{}: {e}", src.display()))?;
    save(name, &text, user, installed, overwrite)
}

/// Rename a user file. Never touches installed folders.
pub fn rename(old: &str, new: &str, user: &Path, installed: &[PathBuf], overwrite: bool) -> Result<PathBuf, String> {
    let from = user_path(old, user, &[])?;
    if !from.is_file() {
        return Err(format!("{old} is not a user pipe file"));
    }
    let to = user_path(new, user, installed)?;
    if to.exists() && !overwrite {
        return Err(format!("{new} already exists"));
    }
    std::fs::rename(&from, &to).map_err(|e| format!("{old}: {e}"))?;
    Ok(to)
}

/// Delete a user file (the caller confirmed).
pub fn delete(name: &str, user: &Path) -> Result<(), String> {
    let path = user_path(name, user, &[])?;
    if !path.is_file() {
        return Err(format!("{name} is not a user pipe file"));
    }
    std::fs::remove_file(&path).map_err(|e| format!("{name}: {e}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp(tag: &str) -> (PathBuf, PathBuf, PathBuf) {
        let d = std::env::temp_dir().join(format!("hs-pipes-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        let inst = d.join("modems");
        std::fs::create_dir_all(&inst).unwrap();
        std::fs::set_permissions(&inst, std::fs::Permissions::from_mode(0o755)).unwrap();
        std::fs::write(inst.join("commander-demod-p25.rxpipe"), "#!/bin/sh\necho installed\n").unwrap();
        std::fs::set_permissions(inst.join("commander-demod-p25.rxpipe"), std::fs::Permissions::from_mode(0o755)).unwrap();
        (d.clone(), inst, d.join("modems.d"))
    }
    fn mode(p: &Path) -> u32 {
        std::fs::metadata(p).unwrap().permissions().mode() & 0o777
    }

    #[test]
    fn names_are_validated() {
        let (_d, inst, user) = tmp("names");
        let i = vec![inst];
        assert!(check_new("my-fm.rxpipe", &user, &i).is_ok());
        for bad in ["My.rxpipe", "a b.rxpipe", "x.sh", "../x.rxpipe", "sub/x.rxpipe", ".x.rxpipe", "x;y.txpipe"] {
            assert!(check_new(bad, &user, &i).is_err(), "{bad}");
        }
        assert!(check_new("commander-demod-p25.rxpipe", &user, &i).unwrap_err().contains("installed"));
        assert_eq!(slug_for("/usr/local/bin/dsdccx -i - -o -", ".rxpipe"), "custom-dsdccx.rxpipe");
        assert_eq!(slug_for("  ", ".txpipe"), "custom-custom.txpipe");
    }

    #[test]
    fn save_dup_rename_delete_rules() {
        let (_d, inst, user) = tmp("ops");
        let i = vec![inst.clone()];
        let p = save("a.rxpipe", &template("a.rxpipe"), &user, &i, false).unwrap();
        assert_eq!(mode(&p), 0o750);
        assert_eq!(mode(&user), 0o750);
        assert!(save("a.rxpipe", "x", &user, &i, false).unwrap_err().contains("exists"));
        save("a.rxpipe", "#!/bin/sh\nexec cat\n", &user, &i, true).unwrap();
        assert_eq!(std::fs::read_to_string(&p).unwrap(), "#!/bin/sh\nexec cat\n");
        let dirs = vec![inst.clone(), user.clone()];
        assert!(MODEMS.resolve("modems/a.rxpipe", &dirs).is_ok());
        // installed files are never written, renamed or deleted
        assert!(save("commander-demod-p25.rxpipe", "x", &user, &i, true).is_err());
        let src = inst.join("commander-demod-p25.rxpipe");
        let dup = duplicate(&src, "my-p25.rxpipe", &user, &i, false).unwrap();
        assert_eq!(std::fs::read_to_string(dup).unwrap(), "#!/bin/sh\necho installed\n");
        assert!(rename("commander-demod-p25.rxpipe", "z.rxpipe", &user, &i, false).is_err());
        assert!(delete("commander-demod-p25.rxpipe", &user).is_err());
        assert!(src.is_file() && mode(&src) == 0o755);
        assert!(rename("a.rxpipe", "my-p25.rxpipe", &user, &i, false).unwrap_err().contains("exists"));
        rename("a.rxpipe", "b.rxpipe", &user, &i, false).unwrap();
        assert!(!user.join("a.rxpipe").exists() && user.join("b.rxpipe").is_file());
        delete("b.rxpipe", &user).unwrap();
        assert!(!user.join("b.rxpipe").exists());
        assert!(delete("../modems/commander-demod-p25.rxpipe", &user).is_err());
    }

    #[test]
    fn wrapper_round_trip() {
        let (_d, inst, user) = tmp("wrap");
        let i = vec![inst.clone()];
        let cmd = "dsdccx -i - -o - | sox -t raw -r 8000 -e signed -b 16 -c 1 - -t raw -r 48000 -";
        let name = slug_for(cmd, ".rxpipe");
        let text = wrapper(&name, cmd, "2026-10-27");
        assert!(text.starts_with("#!/bin/sh\n") && text.contains("2026-10-27") && text.ends_with(&format!("{cmd}\n")));
        let p = save(&name, &text, &user, &i, false).unwrap();
        assert_eq!(mode(&p), 0o750);
        assert!(save(&name, &text, &user, &i, false).is_err(), "no silent overwrite");
        let dirs = vec![inst, user];
        let stored = MODEMS.reference(&name);
        assert_eq!(MODEMS.resolve(&stored, &dirs).unwrap(), p);
        let ok = std::process::Command::new("sh").arg("-n").arg(&p).status().unwrap();
        assert!(ok.success());
    }
}
